"""Real PrusaSlicer 2.9.6 single plate; generic 3D45-sized PLA estimate."""
import json,math,subprocess,zipfile
import trimesh
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2];OUT=ROOT/'models/L2_r3';RP=ROOT/'reports/l2_r3';WORK=ROOT/'_support/work/l2_r3/slice'
SL=ROOT/'_support/tools/PrusaSlicer/PrusaSlicer-2.9.6/prusa-slicer-console.exe'
def run(args,label):
    with (WORK/(label+'.log')).open('w',encoding='utf8') as stream:
        subprocess.run([str(SL),'--sw-renderer','--threads','1','--datadir',str(ROOT/'_support/config/PrusaSlicer'),*map(str,args)],stdout=stream,stderr=subprocess.STDOUT,check=True,timeout=1500)
def main():
    WORK.mkdir(parents=True,exist_ok=True)
    ini=Path(__file__).with_name('PLA_0.4_0.20_ESTIMATE.ini')
    text=(ROOT/'cad/rebuild_r3_2/PLA_0.4_0.20_ESTIMATE.ini').read_text()
    text=text.replace('220x0,220x220,0x220','255x0,255x155,0x155').replace('220mm','255x155mm').replace('R3_2','L2_r3').replace('brim_width = 4','brim_width = 2')
    ini.write_text(text,encoding='utf8')
    scene=trimesh.Scene();x=y=8.;rowh=0.;placements=[]
    names=json.loads((RP/'assembly_inventory.json').read_text())['printable']
    names.sort(key=lambda n:0 if n=='BODY' else 1)
    for n in names:
        m=trimesh.load_mesh(OUT/'parts'/(n+'.stl'))
        rotation=90 if n=='WHEEL' else 0
        if rotation:m.apply_transform(trimesh.transformations.rotation_matrix(math.pi/2,[0,1,0]))
        w,h,z=m.extents
        if x+w>247:x=8;y+=rowh+12;rowh=0
        assert y+h<=147,(n,'plate overflow',y+h)
        shift=[x-m.bounds[0,0],y-m.bounds[0,1],-m.bounds[0,2]];m.apply_translation(shift)
        scene.add_geometry(m,node_name=n,geom_name=n);placements.append(dict(name=n,rotation_y_deg=rotation,translation_mm=shift,bounds_mm=m.bounds.tolist(),size_mm=m.extents.tolist()))
        x+=w+12;rowh=max(rowh,h)
    scene.units='mm';raw=WORK/'raw_plate.3mf';raw.write_bytes(trimesh.exchange.threemf.export_3MF(scene))
    target=OUT/'L2_r3_H_ALL_PARTS_SINGLE_PLATE.3mf'
    run(['--load',ini,'--dont-arrange','--export-3mf','--output',target,raw],'export')
    full=WORK/'full.ini';run(['--load',ini,'--save',full],'profile')
    with zipfile.ZipFile(target) as z:files={n:z.read(n) for n in z.namelist()}
    cfg='; generated by PrusaSlicer 2.9.6; L2-r3 estimate\n'+''.join('; '+l+'\n' for l in full.read_text().splitlines() if ' = ' in l and not l.startswith('#'))
    files['Metadata/Slic3r_PE.config']=cfg.encode()
    with zipfile.ZipFile(target,'w',zipfile.ZIP_DEFLATED) as z:
        for n,data in files.items():z.writestr(n,data)
    gcode=WORK/'validation_only.gcode';run(['--dont-arrange','--export-gcode','--output',gcode,target],'slice')
    run(['--info',target],'info')
    footer={};role='UNKNOWN';extrusion={};epos=0.
    import re
    for line in gcode.read_text().splitlines():
        if line.startswith('; ') and ' = ' in line:
            key,value=line[2:].split(' = ',1);footer[key]=value
        if line.startswith(';TYPE:'):role=line[6:]
        if line.startswith(('G1 ','G2 ','G3 ')) and ' E' in line:
            m=re.search(r' E([-+\d.]+)',line)
            if m and (' X' in line or ' Y' in line):extrusion[role]=extrusion.get(role,0)+max(0,float(m.group(1)))
    factor=math.pi*(1.75/2)**2*1.24/1000
    roles={k:v*factor for k,v in extrusion.items()}
    save=dict(slicer='PrusaSlicer 2.9.6',status='REAL_SLICE_ESTIMATE_NOT_PRINTER_CERTIFIED',bed_mm=[255,155],assumption='Dremel 3D45 bed footprint only; generic Marlin estimate, no machine-specific G-code delivered',placements=placements,embedded_settings={k:footer.get(k) for k in ['nozzle_diameter','layer_height','filament_density','bed_shape']},total_filament_g=footer.get('filament used [g]'),time=footer.get('estimated printing time (normal mode)'),extrusion_roles_g=roles,role_mass_method='Positive XY extrusion by G-code TYPE, relative E; excludes standalone retract/reprime',scale=1.)
    (RP/'slice_summary.json').write_text(json.dumps(save,indent=2))
    (RP/'slicer_model_info.txt').write_text((WORK/'info.log').read_text())
    print(json.dumps(save,indent=2),flush=True)
if __name__=='__main__':main()
